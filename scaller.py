"""
Helper module for loading scalers for the different model variants
Handles both the 11D scaler (without wine type) and the 12D scaler (with wine
type)
"""

import pickle
import os
from typing import Tuple, Optional
from sklearn.preprocessing import StandardScaler


def load_scalers(dataset: str = 'wine') -> Tuple[Optional[StandardScaler], Optional[StandardScaler]]:
    """
    Load the scalers for the given dataset.

    Args:
        dataset: 'wine' (default) or 'concrete' - determines the file paths

    Returns:
        Tuple: (scaler_11D, scaler_12D)
    """
    scaler_11 = None
    scaler_12 = None

    # Default paths for the wine dataset
    if dataset == 'wine':
        scaler_path_11 = os.path.join('models', 'scaler.pkl')
        scaler_path_12 = os.path.join('models', 'scaler_nn.pkl')
    else:
        # Other datasets (e.g. concrete) use the structure: models/<dataset>/
        scaler_path_11 = os.path.join('models', dataset, 'scaler.pkl')
        scaler_path_12 = os.path.join('models', dataset, 'scaler_nn.pkl')

    if os.path.exists(scaler_path_11):
        try:
            with open(scaler_path_11, 'rb') as f:
                scaler_11 = pickle.load(f)
            print(f"✓ Loaded scaler 11D: {scaler_path_11}")
        except Exception as e:
            print(f"⚠ Error loading scaler 11D: {e}")

    if os.path.exists(scaler_path_12):
        try:
            with open(scaler_path_12, 'rb') as f:
                scaler_12 = pickle.load(f)
            print(f"✓ Loaded scaler 12D: {scaler_path_12}")
        except Exception as e:
            print(f"⚠ Error loading scaler 12D: {e}")

    # If both scalers are missing, no warning is shown at the module level
    # (the notification should be generated by the UI in the appropriate context)

    return scaler_11, scaler_12


def get_scaler_11d(dataset: str = 'wine') -> Optional[StandardScaler]:
    """
    Load only the 11D scaler (intended for the ANFIS model).

    Returns:
        StandardScaler object, or None if the file does not exist.
    """
    if dataset == 'wine':
        scaler_path = os.path.join('models', 'scaler.pkl')
    else:
        scaler_path = os.path.join('models', dataset, 'scaler.pkl')
    if os.path.exists(scaler_path):
        try:
            with open(scaler_path, 'rb') as f:
                return pickle.load(f)
        except Exception as e:
            print(f"⚠ Error loading scaler 11D: {e}")
    return None


